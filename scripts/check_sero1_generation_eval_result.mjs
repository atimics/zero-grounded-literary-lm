#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";

function read(path) { return JSON.parse(fs.readFileSync(path, "utf8")); }
function assert(condition, message) { if (!condition) throw new Error(message); }
function close(actual, expected, tolerance = 1e-12) {
  return Math.abs(actual - expected) <= tolerance * Math.max(1, Math.abs(expected));
}
function mean(values) { return values.reduce((sum, value) => sum + value, 0) / values.length; }

const base = "benchmarks/sero1-generation-eval-v1";
const contractPath = `${base}/contract.json`;
const resultPath = `${base}/result.json`;
const reportPath = `${base}/RESULT.md`;
for (const path of [contractPath, resultPath, reportPath]) {
  assert(fs.existsSync(path), `missing Sero 1 generation evaluation artifact: ${path}`);
}

const contractBytes = fs.readFileSync(contractPath);
const contractDigest = crypto.createHash("sha256").update(contractBytes).digest("hex");
const contract = JSON.parse(contractBytes);
const result = read(resultPath);
const pretrain = read("benchmarks/sero1-pretrain-v1/contract.json");

assert(contract.schema === "sero.generation_eval_contract.v1", "wrong evaluation contract schema");
assert(result.schema === "sero.generation_eval_result.v1", "wrong evaluation result schema");
assert(result.contract_sha256 === contractDigest, "evaluation contract binding drifted");
assert(result.source_experiment === contract.source_experiment,
  "source experiment binding drifted");
assert(result.dataset_digest === pretrain.data.dataset_digest,
  "held-out dataset binding drifted");
assert(result.tokenizer_sha256 === contract.tokenizer_sha256,
  "evaluation tokenizer binding drifted");

const seeds = Object.keys(contract.checkpoint_sha256_by_seed).map(Number).sort((a, b) => a - b);
assert(JSON.stringify(result.checkpoints.map((row) => row.seed)) === JSON.stringify(seeds),
  "evaluation checkpoint seed ordering drifted");
for (const row of result.checkpoints) {
  assert(Object.keys(row).sort().join(",") === "seed,sha256",
    `seed ${row.seed} result leaks a machine-local checkpoint path`);
  assert(row.sha256 === contract.checkpoint_sha256_by_seed[String(row.seed)],
    `seed ${row.seed} checkpoint hash drifted`);
}

const context = contract.held_out_context;
const promptLengths = [...context.prompt_token_lengths].sort((a, b) => a - b);
const sources = new Set(result.held_out_cases.map((row) => row.source_id));
const expectedCases = sources.size * context.documents_per_source;
assert(result.held_out_cases.length === expectedCases, "held-out case count drifted");
for (const source of sources) {
  assert(result.held_out_cases.filter((row) => row.source_id === source).length ===
    context.documents_per_source, `held-out source balance drifted for ${source}`);
}
const expectedHeldOutRows = seeds.length * expectedCases * promptLengths.length;
assert(result.held_out_evaluations.length === expectedHeldOutRows,
  "held-out evaluation row count drifted");
const heldOutKeys = new Set();
for (const row of result.held_out_evaluations) {
  const key = `${row.seed}\0${row.case_id}\0${row.prompt_tokens}`;
  assert(!heldOutKeys.has(key), `duplicate held-out row ${key}`);
  heldOutKeys.add(key);
  assert(seeds.includes(row.seed) && promptLengths.includes(row.prompt_tokens),
    `held-out row is outside the contract: ${key}`);
  assert(row.reference_score.reference_tokens === context.continuation_tokens,
    `held-out reference length drifted: ${key}`);
  assert(row.generation.metrics.tokens === context.continuation_tokens,
    `held-out generation length drifted: ${key}`);
}

const decoderRepeats = Object.fromEntries(
  contract.free_generation.decoders.map((row) => [row.id, row.repeats]),
);
const expectedFreeRows = seeds.length * contract.free_generation.prompts.length *
  Object.values(decoderRepeats).reduce((sum, value) => sum + value, 0);
assert(result.free_generations.length === expectedFreeRows,
  "free-generation row count drifted");
const freeKeys = new Set();
for (const row of result.free_generations) {
  const key = `${row.seed}\0${row.prompt_id}\0${row.decoder}\0${row.repeat}`;
  assert(!freeKeys.has(key), `duplicate free-generation row ${key}`);
  freeKeys.add(key);
  assert(seeds.includes(row.seed) && row.repeat >= 0 && row.repeat < decoderRepeats[row.decoder],
    `free-generation row is outside the contract: ${key}`);
  assert(row.generation.metrics.tokens === contract.free_generation.new_tokens,
    `free-generation length drifted: ${key}`);
  assert(row.generation.generated_bytes_hex.length === row.generation.metrics.bytes * 2,
    `generated byte accounting drifted: ${key}`);
  const distinct4 = row.generation.metrics.token_ngrams["4"].distinct_ratio;
  assert(distinct4 >= 0 && distinct4 <= 1 &&
    typeof row.generation.metrics.severe_loop === "boolean",
  `generation metrics are invalid: ${key}`);
}

const contextSummary = result.summaries.held_out_by_prompt_length;
assert(JSON.stringify(contextSummary.map((row) => row.prompt_tokens)) ===
  JSON.stringify(promptLengths), "context summary ordering drifted");
for (const row of contextSummary) {
  const matching = result.held_out_evaluations.filter(
    (value) => value.prompt_tokens === row.prompt_tokens,
  );
  assert(row.count === matching.length && close(row.mean_reference_bits_per_byte,
    mean(matching.map((value) => value.reference_score.bits_per_byte))),
  `context summary mean drifted at ${row.prompt_tokens} tokens`);
}
assert(result.summaries.paired_context_gains.length === promptLengths.length - 1,
  "paired context summary count drifted");
const report = fs.readFileSync(reportPath, "utf8");
assert(report.includes("This is a post-training diagnostic, not a new promotion gate") &&
  report.includes("Sampling can expose usable probability mass"),
"evaluation report lost its scope warning");

console.log(
  `Sero 1 generation evaluation passed; held-out=${expectedHeldOutRows}, free=${expectedFreeRows}`,
);
